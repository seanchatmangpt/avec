#!/bin/sh
# scripts/footprint.sh — wasm32-wasip1 footprint gate for avec-arrow + avec-parquet.
# Charter CTQ-4: <= 100 KiB stripped (target), 250 KiB USL.
#
# Why a harness crate: avec-arrow/avec-parquet are #![no_std] + alloc libs that
# deliberately omit #[panic_handler]/#[global_allocator] (consumers supply them),
# so a direct `cargo rustc --crate-type cdylib` cannot link. This script mints a
# throwaway harness crate in /tmp (scratch, never inside the repo) that:
#   - `pub use`-re-exports each crate's full public API, making every pub item a
#     linker root, so the WHOLE public surface is retained and measured;
#   - supplies minimal disclosed no_std link glue (panic handler; a never-called
#     GlobalAlloc) so the cdylib links;
#   - mirrors the repo [profile.release] (lto = thin, codegen-units = 1).
# Output is wasm-opt -Oz'd (no -g => name/debug sections dropped = stripped).
# Gate: exit 0 iff COMBINED stripped size <= USL (250 KiB).
set -eu

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"

TARGET="wasm32-wasip1"
OPT_BIN="/opt/homebrew/bin/wasm-opt"
OUT_DIR="${TMPDIR:-/tmp}/avec-wasm-footprint"
DOC="docs/wasm-footprint.txt"

TARGET_BYTES=102400   # 100 KiB charter target (CTQ-4)
USL_BYTES=256000      # 250 KiB upper spec limit

rm -rf "$OUT_DIR"
mkdir -p "$OUT_DIR"

echo "== avec WASM footprint gate =="
echo "rustc:    $(rustc --version)"
echo "cargo:    $(cargo --version)"
echo "wasm-opt: $("$OPT_BIN" --version)"
echo "target:   $TARGET"

# ---------------------------------------------------------------------------
# Scratch harness crate(s) in /tmp. Each re-exports one crate's public API.
# ---------------------------------------------------------------------------
mk_harness() {
    name="$1"; shift
    dir="$OUT_DIR/$name"
    mkdir -p "$dir/src"
    {
        echo '[package]'
        echo "name = \"$name\""
        echo 'version = "0.0.0"'
        echo 'edition = "2021"'
        echo ''
        echo '[lib]'
        echo 'crate-type = ["cdylib"]'
        echo ''
        echo '[dependencies]'
        for pkg_path in "$@"; do
            pkg_name=${pkg_path##*/}
            echo "$pkg_name = { path = \"$pkg_path\" }"
        done
        echo ''
        echo '[profile.release]'
        echo 'lto = "thin"'
        echo 'codegen-units = 1'
        echo ''
        echo '[workspace]'
    } > "$dir/Cargo.toml"

    dep_uses=""
    for pkg_path in "$@"; do
        crate_name=$(printf '%s' "${pkg_path##*/}" | tr '-' '_')
        dep_uses="${dep_uses}pub use ${crate_name}::*;"
    done

    {
        echo '//! Footprint-measurement harness (generated by scripts/footprint.sh'
        echo '//! into /tmp scratch; never committed). Re-exports the full public API'
        echo '//! of the measured crates so every pub item is a linker root, and'
        echo '//! supplies the no_std link glue the measured libs intentionally omit.'
        echo '#![no_std]'
        echo ''
        echo 'use core::alloc::{GlobalAlloc, Layout};'
        echo ''
        echo '/// Disclosed measurement glue: never called (no code executes in a'
        echo '/// footprint artifact). Satisfies the linker; adds ~0 bytes.'
        echo 'struct NullAlloc;'
        echo 'unsafe impl GlobalAlloc for NullAlloc {'
        echo '    unsafe fn alloc(&self, _: Layout) -> *mut u8 { core::ptr::null_mut() }'
        echo '    unsafe fn dealloc(&self, _: *mut u8, _: Layout) {}'
        echo '}'
        echo ''
        echo '#[global_allocator]'
        echo 'static A: NullAlloc = NullAlloc;'
        echo ''
        echo '#[panic_handler]'
        echo 'fn ph(_: &core::panic::PanicInfo) -> ! {'
        echo '    loop {}'
        echo '}'
        echo ''
        printf '%s\n' "$dep_uses"
    } > "$dir/src/lib.rs"
}

mk_harness avec-arrow-fp "$ROOT/crates/avec-arrow"
mk_harness avec-parquet-fp "$ROOT/crates/avec-parquet"
mk_harness avec-total-fp "$ROOT/crates/avec-arrow" "$ROOT/crates/avec-parquet"

export CARGO_TARGET_DIR="$OUT_DIR/target"

build_and_measure() {
    name="$1"
    echo "-- building harness: $name" >&2
    (cd "$OUT_DIR/$name" && cargo build --release --target "$TARGET")
    src_artifact=$(printf '%s' "$name" | tr '-' '_')
    src="$CARGO_TARGET_DIR/$TARGET/release/$src_artifact.wasm"
    if [ ! -f "$src" ]; then
        echo "ERROR: expected wasm artifact not found: $src" >&2
        exit 2
    fi
    opt="$OUT_DIR/$name.opt.wasm"
    "$OPT_BIN" -Oz "$src" -o "$opt"
    raw=$(wc -c < "$src" | tr -d ' ')
    bytes=$(wc -c < "$opt" | tr -d ' ')
    printf '%s %s %s\n' "$name" "$raw" "$bytes"
}

arrow_row=$(build_and_measure avec-arrow-fp)
parquet_row=$(build_and_measure avec-parquet-fp)
total_row=$(build_and_measure avec-total-fp)

arrow_bytes=$(printf '%s' "$arrow_row" | awk '{print $3}')
parquet_bytes=$(printf '%s' "$parquet_row" | awk '{print $3}')
total=$(printf '%s' "$total_row" | awk '{print $3}')
arrow_raw=$(printf '%s' "$arrow_row" | awk '{print $2}')
parquet_raw=$(printf '%s' "$parquet_row" | awk '{print $2}')
total_raw=$(printf '%s' "$total_row" | awk '{print $2}')

target_met=false
usl_met=false
if [ "$total" -le "$TARGET_BYTES" ]; then target_met=true; fi
if [ "$total" -le "$USL_BYTES" ]; then usl_met=true; fi

if [ "$target_met" = true ]; then
    target_verdict="PASS (combined <= $TARGET_BYTES bytes = 100 KiB charter target)"
else
    target_verdict="FAIL (combined > $TARGET_BYTES bytes = 100 KiB charter target)"
fi
if [ "$usl_met" = true ]; then
    usl_verdict="PASS (combined <= $USL_BYTES bytes = 250 KiB USL)"
    gate="GATE: PASS"
else
    usl_verdict="FAIL (combined > $USL_BYTES bytes = 250 KiB USL)"
    gate="GATE: FAIL"
fi

echo ""
echo "== footprint: raw cdylib -> wasm-opt -Oz (stripped) =="
printf 'avec-arrow   raw=%s optimized_stripped=%s\n' "$arrow_raw" "$arrow_bytes"
printf 'avec-parquet raw=%s optimized_stripped=%s\n' "$parquet_raw" "$parquet_bytes"
printf 'COMBINED (single-link, glue once) raw=%s optimized_stripped=%s bytes\n' "$total_raw" "$total"
echo "TARGET (100 KiB): $target_verdict"
echo "USL (250 KiB):    $usl_verdict"
echo "$gate"

# Regenerate the docs artifact from the real measured numbers.
{
    echo "# avec wasm32-wasip1 footprint: avec-arrow + avec-parquet"
    echo ""
    echo "Generated by: scripts/footprint.sh (idempotent; regenerates this file)"
    echo "Target: wasm32-wasip1, cdylib via scratch harness crate in /tmp"
    echo "Toolchain: $(rustc --version) / $(cargo --version)"
    echo "Optimizer: $("$OPT_BIN" --version), flags: -Oz (no -g => stripped: name/debug sections dropped)"
    echo ""
    echo "## Method"
    echo ""
    echo "Both crates are #![no_std] + alloc libs whose panic handler and global"
    echo "allocator are supplied by consumers. A throwaway harness crate (minted in"
    echo "/tmp by the script, never committed) pub use-re-exports each crate's full"
    echo "public API so every pub item is a linker root, supplies minimal disclosed"
    echo "no_std link glue (panic handler + never-called GlobalAlloc, ~0 bytes), and"
    echo "mirrors the repo release profile (lto = thin, codegen-units = 1). The"
    echo "COMBINED figure links both crates together so shared core/alloc glue is"
    echo "counted once; per-crate figures come from single-crate harnesses and"
    echo "therefore each include one copy of that glue."
    echo ""
    echo "## Results"
    echo ""
    echo "| crate | raw cdylib (bytes) | wasm-opt -Oz stripped (bytes) |"
    echo "|---|---|---|"
    printf '| avec-arrow | %s | %s |\n' "$arrow_raw" "$arrow_bytes"
    printf '| avec-parquet | %s | %s |\n' "$parquet_raw" "$parquet_bytes"
    printf '| COMBINED (single link) | %s | %s |\n' "$total_raw" "$total"
    echo ""
    echo "## Charter CTQ-4 verdict (combined, stripped)"
    echo ""
    echo "TARGET  <= 100 KiB (102400 bytes): $target_verdict"
    echo "USL     <= 250 KiB (256000 bytes): $usl_verdict"
    echo ""
    echo "$gate (script exit code reflects the USL)"
} > "$DOC"

if [ "$usl_met" = true ]; then
    exit 0
fi
exit 1
