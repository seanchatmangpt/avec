#!/bin/sh
# scripts/footprint.sh — wasm32-wasip1 footprint gate for avec-arrow + avec-parquet.
# Charter CTQ-4: <= 100 KiB stripped (target), 250 KiB USL.
# Builds both crates as cdylib (they are plain lib crates; --crate-type cdylib
# overrides the rlib default for this measurement without touching manifests),
# optimizes with wasm-opt -Oz (no -g => name/debug sections dropped = stripped),
# and gates the COMBINED byte size. Exit 0 iff total <= USL.
set -eu

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"

TARGET="wasm32-wasip1"
OPT_BIN="/opt/homebrew/bin/wasm-opt"
OUT_DIR="${TMPDIR:-/tmp}/avec-wasm-footprint"
DOC="docs/wasm-footprint.txt"

TARGET_BYTES=102400   # 100 KiB charter target (CTQ-4)
USL_BYTES=256000      # 250 KiB upper spec limit

mkdir -p "$OUT_DIR"

echo "== avec WASM footprint gate =="
echo "rustc:   $(rustc --version)"
echo "cargo:   $(cargo --version)"
echo "wasm-opt: $("$OPT_BIN" --version)"
echo "target:  $TARGET"

# Build one package as a wasm cdylib.
build_cdylib() {
    pkg="$1"
    echo "-- cargo rustc --release --target $TARGET -p $pkg --crate-type cdylib"
    cargo rustc --release --target "$TARGET" -p "$pkg" --crate-type cdylib
}

build_cdylib avec-arrow
build_cdylib avec-parquet

total=0
report="$OUT_DIR/rows.txt"
: > "$report"

for pkg in avec-arrow avec-parquet; do
    src="target/$TARGET/release/$(printf '%s' "$pkg" | tr '-' '_').wasm"
    opt="$OUT_DIR/$pkg.opt.wasm"
    if [ ! -f "$src" ]; then
        echo "ERROR: expected wasm artifact not found: $src" >&2
        exit 2
    fi
    raw=$(wc -c < "$src" | tr -d ' ')
    "$OPT_BIN" -Oz "$src" -o "$opt"
    bytes=$(wc -c < "$opt" | tr -d ' ')
    printf '%s raw=%s optimized_stripped=%s\n' "$pkg" "$raw" "$bytes" >> "$report"
    total=$((total + bytes))
done

target_met=false
usl_met=false
if [ "$total" -le "$TARGET_BYTES" ]; then
    target_met=true
fi
if [ "$total" -le "$USL_BYTES" ]; then
    usl_met=true
fi

if [ "$target_met" = true ]; then
    target_verdict="PASS (<= ${TARGET_BYTES} bytes / 100 KiB charter target)"
else
    target_verdict="FAIL (> ${TARGET_BYTES} bytes / 100 KiB charter target)"
fi
if [ "$usl_met" = true ]; then
    usl_verdict="PASS (<= ${USL_BYTES} bytes / 250 KiB USL)"
    gate="GATE: PASS"
else
    usl_verdict="FAIL (> ${USL_BYTES} bytes / 250 KiB USL)"
    gate="GATE: FAIL"
fi

echo ""
echo "== footprint (stripped, wasm-opt -Oz) =="
cat "$report"
echo "TOTAL: ${total} bytes"
echo "TARGET (100 KiB): $target_verdict"
echo "USL (250 KiB):    $usl_verdict"
echo "$gate"

# Regenerate the docs artifact from the real measured numbers.
{
    echo "# avec wasm32-wasip1 footprint (avec-arrow + avec-parquet)"
    echo ""
    echo "Generated by: scripts/footprint.sh"
    echo "Target: wasm32-wasip1 (cdylib via cargo rustc --crate-type cdylib)"
    echo "Toolchain: $(rustc --version) / $(cargo --version)"
    echo "Optimizer: $("$OPT_BIN" --version), flags: -Oz (no -g => stripped: name/debug sections dropped)"
    echo ""
    echo "Per-crate size (bytes, stripped):"
    sed 's/^/  /' "$report"
    echo ""
    echo "TOTAL combined: $total bytes"
    echo ""
    echo "Charter CTQ-4 target: <= 100 KiB (102400 bytes): $target_verdict"
    echo "USL: <= 250 KiB (256000 bytes): $usl_verdict"
    echo "$gate (script exit code reflects the USL)"
} > "$DOC"

if [ "$usl_met" = true ]; then
    exit 0
fi
exit 1
